ALL_FILEPATH_IGNORE_REGEXES = CASR_CPP_FILEPATH_IGNORE_REGEXES

_COMPILED_FUNCTION_PATTERNS = tuple(
    re.compile(pattern) for pattern in dict.fromkeys(ALL_FUNCTION_IGNORE_REGEXES)
)
_COMPILED_FILEPATH_PATTERNS = tuple(
    re.compile(pattern) for pattern in dict.fromkeys(ALL_FILEPATH_IGNORE_REGEXES)
)


def is_vendored_noise_function(func_name):
    if not func_name:
        return False
    return any(pattern.match(func_name) for pattern in _COMPILED_FUNCTION_PATTERNS)


def is_vendored_noise_filepath(file_path):
    if not file_path:
        return False
    return any(pattern.match(file_path) for pattern in _COMPILED_FILEPATH_PATTERNS)
