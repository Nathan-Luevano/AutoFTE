"""Vendored stack-frame noise-ignore lists from ClusterFuzz and CASR.

**Status: prepared but NOT yet wired into `autofte/dedup.py`.** This module only
assembles the vendored data and a self-contained matcher on top of it; `dedup.py`'s
`_NOISE_FUNC_RE` / `is_noise_frame` are untouched and still drive real bucketing.
Swapping the live denylist over to this module is a separate, later task, gated on
`autofte bench` existing so the before/after effect on inverse purity can be
measured -- see `planning/HARDENING.md` Part 3's "land one at a time, measure"
discipline and `planning/research/05-accuracy-and-ground-truth.md` SS3.6.

Sources (both Apache-2.0; full license text at
https://www.apache.org/licenses/LICENSE-2.0):

- ClusterFuzz, `src/clusterfuzz/stacktraces/constants.py`
  (Copyright 2020 Google LLC), fetched live from
  https://raw.githubusercontent.com/google/clusterfuzz/master/src/clusterfuzz/stacktraces/constants.py
  on 2026-08-07. `STACK_FRAME_IGNORE_REGEXES` (210 entries, verbatim) is reproduced
  below as `CLUSTERFUZZ_FUNCTION_IGNORE_REGEXES`; `STACK_FRAME_IGNORE_REGEXES_IF_SYMBOLIZED`
  (5 entries, verbatim) as `CLUSTERFUZZ_FUNCTION_IGNORE_REGEXES_IF_SYMBOLIZED`.
- CASR / libcasr, `libcasr/src/constants.rs`
  (Copyright 2020 Google LLC, Modifications copyright (C) 2023 ISP RAS), fetched
  live from
  https://raw.githubusercontent.com/ispras/casr/master/libcasr/src/constants.rs
  on 2026-08-07. `STACK_FRAME_FUNCTION_IGNORE_REGEXES_CPP` (156 entries, verbatim --
  CASR ships 157 string literals in this list but one, `r"^main",`, is commented out
  in their source with `//`, so it is correctly excluded here too) is reproduced
  below as `CASR_CPP_FUNCTION_IGNORE_REGEXES`; `STACK_FRAME_FILEPATH_IGNORE_REGEXES_CPP`
  (43 entries, verbatim) as `CASR_CPP_FILEPATH_IGNORE_REGEXES`. This is CASR's C++
  list specifically -- CASR also ships separate Java/JS/Lua/Python/Rust/Go/C# lists
  not relevant to AutoFTE's ASan/UBSan C/C++ target scope.

Both files were fetched over the network from this sandbox and used verbatim, not
reconstructed from training-data memory -- so the counts above are exact, not
estimates. (`planning/HARDENING.md` Part 3 fix #2 cites ClusterFuzz's list as
"~180 patterns" from memory/prior research; the real file has 210. CASR's real C++
function list has 156, not the "~180" figure sometimes attributed to it either --
that estimate conflated it with ClusterFuzz's count. Both real counts are recorded
here so nobody downstream re-guesses.)

`EXTRA_FUNCTION_IGNORE_REGEXES` below adds the four patterns named explicitly in
research/05 SS3.6/SS3.7 that a term-by-term check found genuinely absent from both
ported lists above (not already covered by a broader prefix already present, e.g.
`^__GI_raise` is skipped because `^__GI_` already matches it): `^_Unwind_`,
`^std::__1?::`, `^__pthread_`, `^clone$`. The other names research/05 lists
(`^abort$`, `^raise$`, `^__GI_raise`, `^__GI_abort`, `^gsignal$`, `^malloc$`,
`^free$`, `^calloc$`, `^realloc$`, `^operator new`, `^operator delete`,
`^__cxa_throw`, `^fuzzer::`, `^LLVMFuzzerTestOneInput$`) are already matched by an
entry or a broader prefix already present in the ClusterFuzz/CASR lists above.

Matching semantics mirror how both source projects actually wrote these patterns:
`re.match` (anchored at position 0), with `.*`-prefixed entries used by the source
authors themselves wherever "contains anywhere" was the intent -- so this module
does the same rather than switching to `re.search`, which would change behavior
for the handful of entries that rely on the anchor (e.g. `^<unknown>$`).
"""

